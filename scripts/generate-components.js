#!/usr/bin/env node

/**
 * Component Registry Generator
 * 
 * Automatically scans the components directory and generates
 * the component registry and schema imports.
 * 
 * Run this script whenever you add a new component:
 * node scripts/generate-components.js
 */

const fs = require('fs');
const path = require('path');

const componentsDir = path.join(__dirname, '../src/rendering-engine/components');
const outputFile = path.join(__dirname, '../src/rendering-engine/components-generated.ts');

// Scan for component folders
const folders = fs.readdirSync(componentsDir, { withFileTypes: true })
  .filter(dirent => dirent.isDirectory())
  .map(dirent => dirent.name);

console.log(`Found ${folders.length} components:`, folders.join(', '));

// Generate imports
const componentImports = folders.map(folder => 
  `import { ${folder} } from './components/${folder}';`
).join('\n');

const schemaImports = folders.map(folder => 
  `import ${folder.toLowerCase()}Example from './components/${folder}/example.json';`
).join('\n');

// Generate component map
const componentMap = folders.map(folder => 
  `  ${folder.toLowerCase()}: ${folder},`
).join('\n');

// Generate schema map
const schemaMap = folders.map(folder => 
  `  ${folder.toLowerCase()}: ${folder.toLowerCase()}Example,`
).join('\n');

// Generate exports
const componentExports = folders.map(folder => folder).join(', ');

// Generate the file content
const fileContent = `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * 
 * This file is generated by scripts/generate-components.js
 * Run: node scripts/generate-components.js
 * 
 * To add a new component:
 * 1. Create your component folder: components/YourComponent/
 * 2. Add YourComponent.tsx, example.json, and index.ts
 * 3. Run: node scripts/generate-components.js
 * 4. Done! Component is auto-registered.
 */

// Import all components
${componentImports}

// Import all component examples
${schemaImports}

// Component registry for rendering
export const COMPONENT_REGISTRY = {
${componentMap}
} as const;

// Example registry for AI prompts
export const EXAMPLE_REGISTRY = {
${schemaMap}
} as const;

// Export individual components
export { ${componentExports} };
`;

// Write the generated file
fs.writeFileSync(outputFile, fileContent, 'utf8');

console.log(`✅ Generated: ${outputFile}`);
console.log('✅ Component registry updated!');
